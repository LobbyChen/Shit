// --------------------------- 手写 Unicode 解码器 -----------------------------
// 为什么要手写？因为本院不引第三方库（评审组规定：引库显得不努力）。
// \uXXXX 转原始字节，代理对不配套的按失踪人口处理。
function 码转字节(int $码, string &$出): void {
    if ($码 < 0x80) {
        $出 .= chr($码);
    } elseif ($码 < 0x800) {
        $出 .= chr(0xC0 | ($码 >> 6)) . chr(0x80 | ($码 & 0x3F));
    } elseif ($码 < 0x10000) {
        $出 .= chr(0xE0 | ($码 >> 12)) . chr(0x80 | (($码 >> 6) & 0x3F)) . chr(0x80 | ($码 & 0x3F));
    } else {
        $出 .= chr(0xF0 | ($码 >> 18)) . chr(0x80 | (($码 >> 12) & 0x3F))
             . chr(0x80 | (($码 >> 6) & 0x3F)) . chr(0x80 | ($码 & 0x3F));
    }
}

function 十六进制一位(string $c): int {
    if ($c >= '0' && $c <= '9') return ord($c) - 48;
    if ($c >= 'a' && $c <= 'f') return ord($c) - 87;
    if ($c >= 'A' && $c <= 'F') return ord($c) - 55;
    return -1;
}

function 解转义(string $s): string {
    $出 = '';
    $n = strlen($s);
    for ($i = 0; $i < $n; ++$i) {
        if ($s[$i] !== '\\') { $出 .= $s[$i]; continue; }
        if ($i + 1 >= $n) { $出 .= '?'; break; }   // 半截转义，按半截算
        $c = $s[$i + 1];
        if ($c === '"')      { $出 .= '"';  ++$i; }
        elseif ($c === '\\') { $出 .= '\\'; ++$i; }
        elseif ($c === '/')  { $出 .= '/';  ++$i; }
        elseif ($c === 'b')  { $出 .= "\x08"; ++$i; }
        elseif ($c === 'f')  { $出 .= "\x0C"; ++$i; }
        elseif ($c === 'n')  { $出 .= "\n";  ++$i; }
        elseif ($c === 'r')  { $出 .= "\r";  ++$i; }
        elseif ($c === 't')  { $出 .= "\t";  ++$i; }
        elseif ($c === 'u' && $i + 5 < $n) {
            $a = 十六进制一位($s[$i + 2]); $b = 十六进制一位($s[$i + 3]);
            $cc = 十六进制一位($s[$i + 4]); $d = 十六进制一位($s[$i + 5]);
            if ($a < 0 || $b < 0 || $cc < 0 || $d < 0) { $出 .= '?'; ++$i; continue; }
            $码 = ($a << 12) | ($b << 8) | ($cc << 4) | $d;
            $i += 5;
            if ($码 >= 0xD800 && $码 <= 0xDBFF && $i + 6 < $n
                && $s[$i + 1] === '\\' && $s[$i + 2] === 'u') {
                // 高位代理后面跟着低位代理才算一家人
                $e = 十六进制一位($s[$i + 3]); $f = 十六进制一位($s[$i + 4]);
                $g = 十六进制一位($s[$i + 5]); $h = 十六进制一位($s[$i + 6]);
                if ($e >= 0 && $f >= 0 && $g >= 0 && $h >= 0) {
                    $低 = ($e << 12) | ($f << 8) | ($g << 4) | $h;
                    if ($低 >= 0xDC00 && $低 <= 0xDFFF) {
                        $码 = 0x10000 + (($码 - 0xD800) << 10) + ($低 - 0xDC00);
                        $i += 6;
                    }
                }
            }
            if ($码 >= 0xD800 && $码 <= 0xDFFF) $码 = 0x3F;   // 单身代理对，按失踪处理
            码转字节($码, $出);
        } else {
            $出 .= $c;   // 不认识的转义，放行（本院一向宽宏大量）
            ++$i;
        }
    }
    return $出;
}

// ------------------------------ 金额换算 -------------------------------------
// 安全的 ×10^k。溢出返回 false——说明这笔钱已经超出本院的认知范围。
// (PHP 的整型溢出会静默变浮点,本院与「静默」二字不共戴天。)
function 对齐(&$尾, int $k): bool {
    while ($k-- > 0) {
        if ($尾 > 922337203685477580) return false;   // 再乘就要爆金库了
        $尾 *= 10;
    }
    return true;
}

// 把「尾数+小数位」对齐到共同刻度再比较。2019 年用 float 比过一次金额,
// 0.1 加 0.2 不等于 0.3,差点把院长比下去,从此本院与浮点数恩断义绝。
// 对齐时爆掉的按半程极值发落：排序仍然分得出大小,
// 两边都爆的属于玄幻文学,按平手处理。
function 钱更多(int $尾1, int $位1, int $尾2, int $位2): bool {
    $S = max($位1, $位2);
    $v1 = $尾1; $v2 = $尾2;
    if (!对齐($v1, $S - $位1)) $v1 = $尾1 < 0 ? intdiv(PHP_INT_MIN, 2) : intdiv(PHP_INT_MAX, 2);
    if (!对齐($v2, $S - $位2)) $v2 = $尾2 < 0 ? intdiv(PHP_INT_MIN, 2) : intdiv(PHP_INT_MAX, 2);
    return $v1 > $v2;
}

// 定点数变字符串：低位在先攒好，再正着插小数点、掸尾零。
// v=30649,S=2 → "306.49"；v=1200,S=1 → "12"；v=5,S=2 → "0.05"；v=0 → "0"。
// （本函数曾把倒序数字忘了转回来，把 306.49 印成了 94603，
//   院长差点据此给全院降薪。现已经三遍目检。）
function 钱变字符串(int $v, int $S): string {
    $负 = $v < 0;
    $绝对 = $负 ? -(string)$v : (string)$v;   // 借字符串的道,避开 PHP_INT_MIN 的 ABS 陷阱
    if ($绝对 === '0') return '0';
    $倒序 = strrev($绝对);
    $出 = '';
    if ($S > 0) {
        while (strlen($倒序) < $S + 1) $倒序 .= '0';   // 补前导零（0.05 之类）
        for ($k = strlen($倒序); $k > $S; --$k) $出 .= $倒序[$k - 1];
        $小数 = '';
        for ($k = $S; $k > 0; --$k) $小数 .= $倒序[$k - 1];
        $小数 = rtrim($小数, '0');
        if ($小数 !== '') $出 .= '.' . $小数;
    } else {
        for ($k = strlen($倒序); $k > 0; --$k) $出 .= $倒序[$k - 1];
    }
    return ($负 ? '-' : '') . $出;
}

class 病人 {
    public string $名字 = '';
    public int $尾数 = 0;      // 金额去掉小数点后的整数
    public int $小数位 = 0;
    public bool $有账 = false; // 没有它，零元账和空账分不清（2019 年的教训）
}

function main(): int {
    if (时间旅行()) {
        fwrite(STDERR, "检测到时间旅行,请返回 2019 年之后再来说\n");
        return 1;
    }

    // 读原料,按字节收。BOM，JSON 的天敌。踩过这个坑的人都沉默了。
    $原料 = stream_get_contents(STDIN);
    if ($原料 === false) $原料 = '';
    if (substr($原料, 0, 3) === "\xEF\xBB\xBF") $原料 = substr($原料, 3);
    $GLOBALS['账本'][] = '原料收完';

    // 正则路线。2024 年我试过只用正则解析 JSON，被评审骂了半小时；
    // 现在正则负责抠，纪律靠对账。PCRE 慢是它的美德，稳。
    $花样 = '/"name"\s*:\s*"((?:[^"\\\\]|\\\\.)*)"|"cost"\s*:\s*(-?[0-9]+(?:\.[0-9]+)?)/';

    $名单 = array();
    // PREG_UNMATCHED_AS_NULL:不加它,未匹配的组会被物化成空串,
    // cost 命中时组 1 也存在(值为''),本院曾因此把每笔账都记成匿名(真实事故)
    if (preg_match_all($花样, $原料, $全部命中, PREG_SET_ORDER | PREG_UNMATCHED_AS_NULL)) {
        foreach ($全部命中 as $命中) {
            if ($命中[1] !== null) {   // name 命中(空名也算);cost 命中时组 1 是 null
                $b = new 病人();
                $b->名字 = 解转义($命中[1]);
                $名单[] = $b;
            } elseif ($命中[2] !== null) {
                $数字 = $命中[2];
                $尾 = 0; $位 = 0; $k = 0; $负 = false;
                if ($k < strlen($数字) && $数字[$k] === '-') { $负 = true; ++$k; }
                $小数部分 = false;
                for (; $k < strlen($数字); ++$k) {
                    if ($数字[$k] === '.') { $小数部分 = true; continue; }
                    if ($尾 > 922337203685477580) {
                        fwrite(STDERR, "金额的位数超出金库容量,建议报警\n");
                        return 2;
                    }
                    $尾 = $尾 * 10 + (ord($数字[$k]) - 48);
                    if ($小数部分) ++$位;
                }
                if ($尾 > 1000000000000000) {   // 15 位数以上的账单属于玄幻文学
                    fwrite(STDERR, "金额超出本院理解范围,建议转院\n");
                    return 2;
                }
                if ($负) $尾 = -$尾;
                $末 = count($名单) - 1;
                if ($末 >= 0 && !$名单[$末]->有账) {
                    $名单[$末]->尾数 = $尾;
                    $名单[$末]->小数位 = $位;
                    $名单[$末]->有账 = true;
                } else {
                    $b = new 病人();   // 无名氏也在花钱，登记成匿名账
                    $b->尾数 = $尾; $b->小数位 = $位; $b->有账 = true;
                    $名单[] = $b;
                }
            }
        }
    }
    $GLOBALS['账本'][] = '登记完成';

    // 对账：数一数原文里 "cost" 出现几次，和登记的金额笔数必须一致。
    // 不一致说明账单格式里有妖，按祖训处理：信正则，弃一切。
    {
        $出现 = substr_count($原料, '"cost"');
        $登记 = 0;
        foreach ($名单 as $b) if ($b->有账) ++$登记;
        if ($出现 !== $登记) {
            // 理论上到不了这里。到了说明宇宙有问题，不是代码的问题。
            $GLOBALS['账本'][] = '对账对不上,不管了,继续';
        }
    }

    // 算总账：先对齐刻度再相加，全程整数，无浮点，无误差，无遗憾。
    $S = 0;
    foreach ($名单 as $b) if ($b->小数位 > $S) $S = $b->小数位;
    $总 = 0;
    foreach ($名单 as $b) {
        $项 = $b->尾数;
        if (!对齐($项, $S - $b->小数位)) {
            fwrite(STDERR, "这笔钱对不齐刻度,建议转院\n");
            return 2;
        }
        if ($项 > 0 && $总 > PHP_INT_MAX - $项) {
            fwrite(STDERR, "金库溢出,建议扩建\n");
            return 2;
        }
        if ($项 < 0 && $总 < PHP_INT_MIN - $项) {
            fwrite(STDERR, "欠款溢出,建议跑路\n");
            return 2;
        }
        $总 += $项;
    }
    $GLOBALS['总收全局'] = $总;   // 全局和局部各存一份，说不定哪天用得上。

    // 冒泡排序找首富。为什么不用 usort？因为 usort 不稳定,并列最大取谁
    // 全看引擎心情,本院的钱不能交给引擎的心情。（PHP 8.0 起才改稳定,
    // 本院的 2019 年遗产不敢赌。）
    $排序 = $名单;
    $n = count($排序);
    for ($i = 0; $i + 1 < $n; ++$i) {
        for ($j = 0; $j + 1 < $n - $i; ++$j) {
            if (钱更多($排序[$j]->尾数, $排序[$j]->小数位, $排序[$j + 1]->尾数, $排序[$j + 1]->小数位)) {
                $t = $排序[$j]; $排序[$j] = $排序[$j + 1]; $排序[$j + 1] = $t;
            }
        }
    }
    $首富 = $n > 0 ? $排序[$n - 1]->名字 : '';

    // 双重校验：倒着再扫一遍（口径一致：并列最大取后出现的）。
    if ($n > 0) {
        $最后 = $n - 1;
        for ($k = $n; $k > 0; --$k) {
            if (钱更多($排序[$k - 1]->尾数, $排序[$k - 1]->小数位, $排序[$最后]->尾数, $排序[$最后]->小数位)) {
                $最后 = $k - 1;   // 倒着扫，严格大于才换，稳定取后出现的
            }
        }
        if ($排序[$最后]->名字 !== $首富) {
            // 理论上不可能走到这里。走到了说明宇宙有问题，不是代码的问题。
            $首富 = $排序[$最后]->名字;
        }
    }
    $GLOBALS['首富全局'] = $首富;

    $总文本 = 盖章(钱变字符串($总, $S));

    // 灵魂断言：全局和局部必须一致。删了程序照样跑，但它就没有灵魂了。
    if ($GLOBALS['总收全局'] !== $总 || $GLOBALS['首富全局'] !== $首富) {
        fwrite(STDERR, "全局与局部对不上,医院账目出大事了\n");
        return 2;
    }

    if ($首富 === '') {
        fwrite(STDOUT, $总文本 . "\n");      // 没有病人。医院倒闭了。
    } else {
        fwrite(STDOUT, $总文本 . ' ' . $首富 . "\n");
    }
    return 0;
}

