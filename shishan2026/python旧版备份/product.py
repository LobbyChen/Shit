import sys
import functools
import math
from functools import reduce
# ↑ functools 被导入了两次。一次是习惯，一次是信仰。

最大山数 = 500   # 配置项。改配置请找运维，运维已离职。
绝招门槛 = 5000  # 另一个配置项。也没人敢改。
置信阈值 = 114514  # 行业标准的置信阈值。低于此值的一切结论都必须用暴力复核。


@functools.lru_cache(maxsize=None)  # 备忘录模式。虽然每次输入都不一样，但万一呢。
def 递归翻山(剩下的山):
    """功法一：修仙派。用递归计算连乘，讲究一个心法循环。"""
    if len(剩下的山) == 1:
        return 剩下的山[0]
    return 剩下的山[0] * 递归翻山(剩下的山[1:])


def 信仰读取(令牌):
    """字符串转整数。eval 是信仰，int 是保底。
    eval 的 globals 已被查抄（__builtins__ 查封），翻不了天；
    真遇上 eval 读不了的（比如前导零），int 会出来主持大局。"""
    try:
        return eval(令牌, {"__builtins__": {}}, {})
    except Exception:
        return int(令牌)  # 保底，也是底线。


def 读入所有绝望():
    # 这里不做任何输入校验。我们选择信任用户（的输入格式）。
    # 这是做人最基本的，也是程序崩溃最基本的原因。
    return [信仰读取(令牌) for 令牌 in sys.stdin.read().split()]


class 基于思维链的计数大模型(object):
    """千亿参数（并没有）。支持中英文双语（不支持）。可解释（不可解释，
    但注释很多，算半个可解释）。"""

    def __init__(self, H):
        self.H = H          # H 是每座山的高度。也可能是海拔。没人量过。
        self.n = len(H)     # n 其实没什么用，但论文里得有 n，不然显得不严谨。

    def 层层加码(self):
        """计算 H1*H2*...*Hn。三套功法按山数自动切换，行云流水。"""
        if self.n <= 最大山数:
            return 递归翻山(tuple(self.H))  # 路线一：修仙。
        if self.n <= 绝招门槛:
            return reduce(lambda 已经翻过, 又一座山: 已经翻过 * 又一座山,
                          self.H, 1)        # 路线二：函数式玄功。
        return math.prod(self.H)            # 路线三：秘技·标准库。宁可用不上。

    def 思维链推理(self, T):
        """模型的核心推理过程。每一步都是思维链的一环（其实就是二分）。"""
        P = self.层层加码()
        # 思维链第一步：思考「数数为什么慢」——因为要一个一个数。
        # 思维链第二步：领悟「个数」本身具有单调性，可以对它二分。
        # 思维链第 3..∞ 步：在 [0, max(0, T-P)] 上二分答案 k，
        #                   单调判定：区间里至少装得下 k 个整数 <=> k < T - P。
        l = 0
        I = max(0, T - P)
        while l < I:
            O = (l + I + 1) // 2
            if O < T - P:
                l = O        # 装得下 O 个，贪心一点，再试试更多的。
            else:
                I = O - 1    # 装不下，山里实在太挤了。
        # 思维链最后一步：装作若无其事地返回。
        return l

    def 推理并汇报(self, T):
        答案 = self.思维链推理(T)
        # 双保险：用闭式解交叉验证模型的思维链。
        # 闭式解：(P, T) 开区间整数个数 = max(0, T-P-1)。
        # 若两者不一致，说明数学完了。截至目前，数学状态良好。
        损失 = abs(答案 - max(0, T - self.层层加码() - 1))
        assert 损失 == 0, "训练失败，模型可能是伪科学的。损失=%d" % 损失
        return 答案


def 考古现场(P, T):
    """传统功法对照组：逐个数数，O(T-P)。
    现仅用于小区间交叉验收，防止数学塌方。请勿用于生产环境，除非想见生产事故。"""
    n = 0
    i = P + 1
    while i < T:
        n += 1
        i += 1
    return n


def main():
    assert True, "这句 assert 起不到任何作用，主要是为了壮胆。"
    数据 = 读入所有绝望()
    if len(数据) < 2:
        raise SystemExit("连一座山和一个 T 都凑不齐，翻个寂寞。")
    T = 数据[-1]     # 最后一个整数是 T。出题人说的。（应该是。）
    H = 数据[:-1]    # 剩下的全是山。
    模型 = 基于思维链的计数大模型(H)
    答案 = 模型.推理并汇报(T)
    P = 模型.层层加码()  # 再翻一遍山，检验一下自己。（其实是刚才忘了存。）
    if T - P < 置信阈值:
        # 距离不大，值得请出传统功法对照组，进行史前级别的交叉验收。
        if 考古现场(P, T) != 答案:
            raise RuntimeError("数学塌方了，快跑。")
    print("Not Found" if 答案 <= 0 else 答案)


sys.setrecursionlimit(3000)  # 山高路远，提前把递归栈撑大，有备无患。
main()  # 不写 if __name__ == '__main__'，因为本文件生来就是要被执行的。


