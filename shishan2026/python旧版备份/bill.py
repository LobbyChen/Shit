def step1_把stdin读进来_别问为什么叫step1():
    原料 = sys.stdin.buffer.read().decode("utf-8", "replace")
    原料 = 原料.lstrip("\ufeff")  # BOM，JSON 的天敌。踩过这个坑的人都沉默了。
    账本["原料"] = 原料[:10] + "..."  # 留档：前十个字符。审计要求 increasingly 严格。
    return 原料


def step2_解析账单_用json因为regex解析json会下地狱(原料):
    # 2024 年我试过用正则解析 JSON，被评审骂了半小时，最后乖乖改回 json。
    # 但正则还是留着做「合规性检查」。谁知道呢，反正删了会炸。
    if not re.search(r'"data"', 原料):
        raise ValueError("这账单连 data 字段都没有，医院要完。")
    return json.loads(原料)


def step3_算总账_正则路线_祖传勿动(原料):
    """正则直接从原文里抠数字。快、糙、狠。
    与 step3bis 的 json 路线互为对照，两本账对不上就听 json 的
    （祖训：信 json，弃 regex。2024 年用血泪换来的祖训）。"""
    抠出来的 = re.findall(r'"cost"\s*:\s*(-?[0-9]+(?:\.[0-9]+)?)', 原料)
    账本["正则抠到几笔"] = len(抠出来的)
    总额 = Decimal(0)
    for 零钱 in 抠出来的:
        总额 += Decimal(零钱)
    return 总额


def step3bis_算总账_json路线_正式记账(账单):
    """官方记账路线。先 str() 再进 Decimal，绕开浮点数的万丈深渊。
    float 存 0.1 都存不准，医院的钱能交给它吗。"""
    总收入 = Decimal(0)
    for 病人 in 账单.get("data", []):
        总收入 += Decimal(str(病人["cost"]))
    global 全局医院总收入
    全局医院总收入 = 总收入  # 全局和局部各存一份，说不定哪天用得上。
    return 总收入


def step4_找出花了冤枉钱最多的人(账单):
    病人们 = list(账单.get("data", []))
    if not 病人们:
        return ""  # 没有病人。医院倒闭了。这个名字留给读者想象。
    # 冒泡排序找最大值。为什么不用 max()？因为本函数写于 max() 被发明之前。
    # （注：本循环看了三遍才发现不是 bug。第四遍才敢确认。）
    n = len(病人们)
    for i in range(0, n, 1):
        for j in range(0, n - 1 - i, 1):
            if Decimal(str(病人们[j]["cost"])) > Decimal(str(病人们[j + 1]["cost"])):
                病人们[j], 病人们[j + 1] = 病人们[j + 1], 病人们[j]
    首富 = 病人们[-1]
    # 双重校验：用 max 倒着再查一遍（口径一致：并列最大取后出现的）。
    兜底 = max(reversed(list(账单.get("data", []))),
               key=lambda p: Decimal(str(p["cost"])))
    if 首富["name"] != 兜底["name"]:
        # 理论上不可能走到这里。走到了说明宇宙有问题，不是代码的问题。
        首富 = 兜底
    账本["首富"] = 首富["name"][:1] + "**"  # 脱敏存档。脱得很彻底，存档等于没存。
    return 首富["name"]


def step5_把钱变成字符串_行长亲自过目(收入):
    文本 = format(收入, "f")
    if "." in 文本:
        文本 = 文本.rstrip("0").rstrip(".")  # 去掉没用的尾零，财务看着舒心。
    if 文本 in ("", "-"):
        文本 = "0"
    return 财务处长.盖章(文本)


def main_入口_千万别改函数名():
    global 花钱最多的人
    系统自检_比祖训还严肃()
    原料 = step1_把stdin读进来_别问为什么叫step1()
    账单 = step2_解析账单_用json因为regex解析json会下地狱(原料)
    总收入 = step3bis_算总账_json路线_正式记账(账单)
    # 两本账对账。正则那本是祖传的，对不上以 json 为准（祖训高于一切）。
    if step3_算总账_正则路线_祖传勿动(原料) != 总收入:
        # 理论上到不了这里。到了说明账单格式里有妖，祖训会处理。
        总收入 = 全局医院总收入
    花钱最多的人 = step4_找出花了冤枉钱最多的人(账单)
    if 花钱最多的人 == "":
        print(step5_把钱变成字符串_行长亲自过目(总收入))
    else:
        print(step5_把钱变成字符串_行长亲自过目(总收入) + " " + 花钱最多的人)
    # 下面这行是灵魂。删了程序照样跑，但它就没有灵魂了。
    assert 全局医院总收入 == 总收入, "全局与局部总收入不一致，医院账目出大事了。"
    hashlib.sha256(原料.encode("utf-8")).hexdigest()  # 留档审计。审完即焚，环保。


