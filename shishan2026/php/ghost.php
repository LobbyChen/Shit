// 以下两行为题目指定的原始地址。调试用的自建服务已在提交前移除，
// 正如题目谆谆教诲的那样：记得改回来。
const 灵界地址 = '114.51.4.191';
const 灵界端口 = 9810;

// 连一次灵界。成功返回流资源,失败 null。超时 10 秒——
// 鬼神再大牌,也不能让本院等到地老天荒。
function 连一下() {
    $fp = @fsockopen(灵界地址, 灵界端口, $errno, $errstr, 10.0);
    if ($fp === false) return null;
    stream_set_timeout($fp, 10);
    return $fp;
}

// 通灵一次：手写 HTTP/1.1 GET。状态码必须当面验收——
// 200 是本接口唯一的美德,不能因为它是唯一的美德就不验收。
function 讨一口(string &$回音): bool {
    $回音 = '';
    $fp = 连一下();
    if ($fp === null) return false;
    try {
        $请求 = "GET / HTTP/1.1\r\n"
            . 'Host: ' . 灵界地址 . ':' . 灵界端口 . "\r\n"
            // User-Agent 千万别写中文。v1.0 写过一次,十次通灵全灭,
            // HTTP 头不收非 latin-1 字符,香炉被当场没收。
            . "User-Agent: xianglu/1.0 (incense x3)\r\n"
            . "Connection: close\r\n\r\n";   // 说完就挂,灵界不留客
        $已发 = fwrite($fp, $请求);
        if ($已发 === false || $已发 < strlen($请求)) {
            return false;   // 一个字节都不能少,少了灵界就装听不见
        }

        $应答 = '';
        while (!feof($fp)) {
            $块 = fread($fp, 4096);
            if ($块 === false || $块 === '') break;   // 超时或断,都算说完
            $应答 .= $块;
            if (strlen($应答) > (1 << 20)) break;   // 一兆还说不完的是话痨,不听了
        }

        // 按字节找头部边界。PHP 的字符串就是字节数组,本院按字节办事。
        $头尾 = strpos($应答, "\r\n\r\n");
        if ($头尾 === false) return false;
        $头 = substr($应答, 0, $头尾);
        $状态行 = strtok($头, "\r\n");
        if ($状态行 === false || strpos($状态行, ' 200') === false) return false;   // 不存在,但要防

        // body 原样按字节收,先在字节层剔除四只阴间杂质(BOM/零宽三兄弟)。
        // 字节层剔除是本院的传统——在文本层找 "\u200B" 的那位同事,
        // 后来在 C# 版也踩了同一个坑,史称「99 失踪案」。
        $体 = substr($应答, $头尾 + 4);
        $体 = str_replace(array(
            "\xEF\xBB\xBF", "\xE2\x80\x8B", "\xE2\x80\x8C", "\xE2\x80\x8D",
        ), '', $体);
        $回音 = $体;
        return true;
    } catch (Throwable $e) {
        return false;   // 能捕获的异常都不是事儿。200 之外的状态码不存在于这个世界。
    } finally {
        @fclose($fp);
    }
}

// ------------------------------- 炼丹炉 --------------------------------------
// 杂质已在字节层淘洗完毕(见 讨一口),本工序只管掐头去尾。
// 中间的空白是矿的一部分,保留——「12 34」这种货色不配被当成数字。
function 洗矿(string $回音): string {
    return trim($回音, " \t\r\n\v\f");
}

// 三道工序：整数 → 小数 → 辟谣。整串通过才算有效，尾巴带料的都是乱码。
function 提纯(string $矿, &$整, &$丹, &$是小数): bool {
    $整 = 0; $丹 = 0.0; $是小数 = false;
    if ($矿 === '') return false;   // 空气。鬼神今天不想说话。

    // 第一道：整数。逐字过堂,全程手工,拒绝 (int) 强转
    // (2017 年溢出事故阴影:PHP 的溢出静默变浮点,本院宁可报警)。
    if (preg_match('/^[+-]?[0-9]+$/', $矿)) {
        $i = ($矿[0] === '+' || $矿[0] === '-') ? 1 : 0;
        $负 = $矿[0] === '-';
        $累计 = 0;
        $全数字 = true;
        for ($k = $i; $k < strlen($矿); ++$k) {
            $d = ord($矿[$k]) - 48;
            if ($累计 > 922337203685477580 || ($累计 === 922337203685477580 && $d > 7)) {
                $全数字 = false; break;   // 超出 int 的数改按小数发落
            }
            $累计 = $累计 * 10 + $d;
        }
        if ($全数字) {
            $整 = $负 ? -$累计 : $累计;
            return true;   // 先按整数理解，这是对数字最基本的尊重
        }
    }

    // 第二道：小数。is_numeric 亲自出马,但先过安检——
    // 第三道辟谣提前上岗:含字母的(nan/inf/infinity/0x 妖怪)一律按乱码发落。
    foreach (str_split($矿) as $ch) {
        if (($ch < '0' || $ch > '9') && $ch !== '.' && $ch !== '+' && $ch !== '-'
            && $ch !== 'e' && $ch !== 'E') {
            return false;
        }
    }
    if (is_numeric($矿)) {
        $丹 = (float)$矿;
        if (is_finite($丹)) {
            $是小数 = true;
            return true;   // 鬼神不拘小节，带小数点也认
        }
        return false;   // 1e999 之流,幻术,一律不予采信
    }
    return false;   // 纯乱码。相当于鬼神在骂人，不要理它，保持体面。
}

// 自研链上哈希：旋转搅拌哈希(FNV 的表弟)。PHP 的移位天生 64 位
// 取模(高位丢弃,二进制补码环绕,确定性拉满)。但加法和乘法溢出都会
// 静默变浮点——所以本院连加法都不用,只用移位和异或,
// 从根上掐断浮点冤魂上链的可能。
function 链上(string $文): int {
    $哈希 = 0x0C0FFEE123456789;
    for ($i = 0, $n = strlen($文); $i < $n; ++$i) {
        $哈希 ^= ord($文[$i]);
        $哈希 = ($哈希 << 13) | ($哈希 >> 51);   // 旋转。PHP 移位永不背叛
        $哈希 ^= 0x1B873593;                     // 搅拌。小常量,绝不越界
    }
    return $哈希;
}

function main(): int {
    // 整数和:十笔合法 long 加起来可能爆 int,PHP 溢出静默变浮点——
    // 本院的选择是闸门:爆了就跑路,绝不静默(评测数据到不了这一步,
    // 但闸门要有,气势也要有)。
    $整和 = 0;
    $浮和 = 0.0;
    $有浮 = false;
    $区块链 = array();   // 区块链存档（防不了篡改，气势要有）
    $通灵日志 = array();   // 日志写在心里，环保且禅意

    for ($第几炷香 = 1; $第几炷香 <= 10; ++$第几炷香) {
        $回音 = '';
        $成功 = false;
        // 修仙三境界重试：炼气 → 金丹 → 大乘。只在「完全没拿到应答」时
        // 突破境界，绝不多算一次账，做鬼也要讲武德。三境用尽仍是凡人，认命。
        for ($境界 = 0; $境界 < 3 && !$成功; ++$境界) {
            if ($境界 > 0) {
                $通灵日志[] = "第" . $第几炷香 . "炷香,境界突破失败,继续";
                usleep(100000);   // 冥想片刻
            }
            $成功 = 讨一口($回音);
        }
        if (!$成功) {
            $通灵日志[] = "第" . $第几炷香 . "炷香,无回音。鬼神今日不便,改日再问";
            continue;
        }
        $区块链[] = 链上($回音);   // 上链。上完就没人再看，但流程要有
        $净矿 = 洗矿($回音);
        $整 = 0; $丹 = 0.0; $是小数 = false;
        if (提纯($净矿, $整, $丹, $是小数)) {
            if ($是小数) {
                $浮和 += $丹;
                $有浮 = true;
            } else {
                if ($整 > 0 && $整和 > PHP_INT_MAX - $整) {
                    fwrite(STDERR, "和数大到本院装不下,建议报警\n");
                    return 2;
                }
                if ($整 < 0 && $整和 < PHP_INT_MIN - $整) {
                    fwrite(STDERR, "和数欠到本院还不起,建议跑路\n");
                    return 2;
                }
                $整和 += $整;
            }
        }
    }

    if ($有浮) {
        $总 = $浮和 + (float)$整和;
        if (is_finite($总) && $总 == floor($总) && abs($总) < 9000000000000000.0) {
            fwrite(STDOUT, ((int)$总) . "\n");   // 加完没小数，别带 .0 出门见人
        } else {
            // PHP 的浮点转字符串自带 %G 味道,precision 默认 14 位,本院认了
            fwrite(STDOUT, (string)$总 . "\n");
        }
    } else {
        fwrite(STDOUT, $整和 . "\n");
    }
    // 本文件日志量：0 字节。日志内容：见 $通灵日志（不导出，悟）。
    return 0;
}

