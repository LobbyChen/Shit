class 炼丹炉(object):
    """负责把乱码原矿提纯成有效数字。三道工序，层层甄别。"""

    @staticmethod
    def 洗矿(回音):
        # 乱矿中常混有阴间杂质，先淘洗。
        # 警告：下面那四个字符串看起来是空的，其实里面封印着
        # BOM、零宽空格、零宽非连接符、零宽连接符四只阴间杂质。
        # 「看起来是空串」不等于「是空串」。不服可以把本行拿去拷打。
        # strip 只去两端空白；中间的空白是矿的一部分，保留——
        # 因为「12 34」这种货色不配被当成数字。
        回音 = 回音.strip()
        for 杂质 in ("﻿", "​", "‌", "‍"):
            回音 = 回音.replace(杂质, "")
        return 回音

    @staticmethod
    def 甄别(原矿):
        净矿 = 炼丹炉.洗矿(原矿)
        if 净矿 == "":
            return None  # 空气。鬼神今天不想说话。
        try:
            return int(净矿)  # 第一道：先按整数理解，这是对数字最基本的尊重。
        except ValueError:
            pass  # 不是整数。鬼神说话，向来拐弯抹角。
        try:
            丹 = float(净矿)
            if math.isfinite(丹):
                return 丹  # 第二道：带小数点也认。鬼神不拘小节。
            return None  # nan / inf 是幻术，一律不予采信（第三道：辟谣）。
        except ValueError:
            return None  # 纯乱码。相当于鬼神在骂人，不要理它，保持体面。


class 通灵师(object):
    """持证上岗（证是自印的）。"""

    专线 = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    # ↑ 专线直连：拒绝中间商（系统代理）赚差价，灵界事务必须面谈。

    @classmethod
    def 通灵一次(cls):
        # 修仙三境界重试：炼气 → 金丹 → 大乘。
        # 只在「完全没拿到应答」时才突破境界，绝不多算一次账，
        # 做鬼也要讲武德。三境用尽仍是凡人，认命。
        for 境界 in ("炼气期", "金丹期", "大乘期"):
            try:
                祈求 = urllib.request.Request(
                    鬼神地址,
                    headers={"User-Agent": "xianglu/1.0 (incense x3)"},
                    # 注：User-Agent 千万别写中文。写过一次，十次通灵全灭。
                )
                with 通灵师.专线.open(祈求, timeout=10) as 应答:
                    return 应答.read().decode("utf-8", "replace")
            except Exception:
                # 能捕获的异常都不是事儿。200 之外的状态码不存在于这个世界。
                通灵日志.append("%s境界失败" % 境界)  # 写进心里的日志。
                if 境界 == "大乘期":
                    return None
                time.sleep(0.1)  # 冥想片刻，突破境界再试。
        return None  # 理论上到不了这里，但 Python 不知道，得安抚一下它。


def main():
    总和 = 0
    for 第几炷香 in range(1, 通灵次数 + 1):
        回音 = 通灵师.通灵一次()
        if 回音 is not None:
            区块链存档.append(
                hashlib.sha256(回音.encode("utf-8")).hexdigest())  # 上链。
            丹药 = 炼丹炉.甄别(回音)
            if 丹药 is not None:
                总和 += 丹药
        else:
            通灵日志.append("第%d炷香，无回音" % 第几炷香)  # 心里的日志 +1。
    if isinstance(总和, float) and 总和.is_integer():
        总和 = int(总和)  # 加完刚好没有小数，就别带着 .0 出门见人了。
    print(str(总和))  # 不要问为什么 str 一遍。问就是历史原因。


# 本文件日志量：0 字节。本文件日志内容：见 通灵日志（不导出，悟）。
main()
