// --------------------------- 自研图灵完备虚拟机 ------------------------------
// 核心算法不写明文,以字节码形式加密分发(XOR 0x66,0x66 即 'f',
// for friendship)。指令集共 6 条,研发耗时一个下午。
// HALT 从未被执行,它的存在是为了让指令集凑个整。
define('加密字节码', array(0x67, 0x64, 0x62, 0x65, 0x63, 0x68));

function 虚拟机运行(int $a, int $b, int $c): bool {
    $栈 = array_fill(0, 16, 0);   // 溢出?栈只有 16 格,本院的数字都很谦虚
    $top = 0; $pc = 0;
    while ($pc < 6) {
        $op = 加密字节码[$pc++] ^ 0x66;
        switch ($op) {
            case 1: $栈[$top++] = $a; break;
            case 2: $栈[$top++] = $b; break;
            case 3: $栈[$top++] = $c; break;
            case 4:
                $y = $栈[--$top]; $x = $栈[--$top];
                $栈[$top++] = $x > $y ? $x : $y;
                break;
            case 5:
                $y = $栈[--$top]; $x = $栈[--$top];
                return $x >= $y;   // 直接返回,比较急
            default:
                return false;      // 不认识的指令,装作无事发生
        }
    }
    return false;   // 字节码忘了写 HALT 的保底(不会发生,才六条指令)
}

// 首席架构师:级别最高,从不写明文代码——代码都从字节码里请出来。
function 首席架构师(int $a, int $b, int $c): bool {
    return 虚拟机运行($a, $b, $c);
}

// 数值分析部门:整数平移精确比较。血泪教训:2019 年有位同事用了 double,
// 从此再没有人见过他。本院只收平移后不超过 60 位的病例,超纲一律上报。
function 数值分析部门(int $a, int $b, int $c): bool {
    $m = 0;
    if ($a < $m) $m = $a;
    if ($b < $m) $m = $b;
    if ($c < $m) $m = $c;
    $最高 = $a - $m;
    if ($b - $m > $最高) $最高 = $b - $m;
    if ($c - $m > $最高) $最高 = $c - $m;
    if ($最高 > 60) return 首席架构师($a, $b, $c);   // 超纲,上报,甩锅
    $左 = (1 << ($a - $m)) + (1 << ($b - $m));
    $右 = (1 << ($c - $m));
    return $左 > $右;
}

// 主任医师:专治各种指数过大,收费按指数算。负数属疑难杂症,转院。
// 门槛 61 而不是 62:a=b=62 时 2^62+2^62 会静默变浮点——本院连医院
// 自己都要过闸门,不搞特权。
function 主任医师(int $a, int $b, int $c): bool {
    if ($a < 0 || $b < 0 || $c < 0) return 数值分析部门($a, $b, $c);
    $最大 = max($a, $b, $c);
    if ($最大 > 61) return 数值分析部门($a, $b, $c);   // 病情危重,转院
    return (1 << $a) + (1 << $b) > (1 << $c);   // 朴素暴力,算得动就很强
}

// 逐字审问室:拒绝使用 (int) 强转(2017 年溢出事故阴影,PHP 的溢出
// 会静默变浮点,浮点会静默丢精度,丢了精度会静默答错——三连静默,
// 本院宁可报警也不接)。超 19 位的数字按「本院装不下」拒收。
function 审讯(string $供词): int {
    $i = 0; $负 = false;
    if ($i < strlen($供词) && ($供词[$i] === '+' || $供词[$i] === '-')) {
        $负 = $供词[$i] === '-';
        ++$i;
    }
    if ($i >= strlen($供词)) {
        fwrite(STDERR, "这串供词里没有一个数字,建议报警\n");
        exit(2);
    }
    $累计 = 0;
    for (; $i < strlen($供词); ++$i) {
        $ch = $供词[$i];
        if ($ch < '0' || $ch > '9') {
            fwrite(STDERR, "审讯发现非数字分子,全部遣返\n");
            exit(2);
        }
        $d = ord($ch) - 48;
        if ($累计 > 922337203685477580 || ($累计 === 922337203685477580 && $d > 7)) {
            fwrite(STDERR, "数字长到本院装不下,建议报警\n");
            exit(2);
        }
        $累计 = $累计 * 10 + $d;
    }
    return $负 ? -$累计 : $累计;
}

// 打印服务:打印失败自动重试一次。PHP 的 fwrite 对 stdout 从不失败,
