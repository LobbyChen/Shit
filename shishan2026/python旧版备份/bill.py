import sys
import json
import re
import hashlib
from decimal import Decimal
from datetime import datetime

全局医院总收入 = Decimal(0)  # 用全局变量才有灵魂。
global 花钱最多的人           # 模块级再 global 一次，双保险。全院无人认领的传统。
花钱最多的人 = ""
账本 = {}                     # 工作成果都往里放，供审计（审计从不来）。


class 财务处长(metaclass=type):
    """全院唯一的处长。global 的化身。盖章流程：返回原件。"""

    @staticmethod
    def 盖章(文本):
        return 文本  # 盖章流程已简化：返回原件。审计很满意。


